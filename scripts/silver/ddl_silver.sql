/*
================================================================
Create Silver Layer Tables
================================================================
Script Purpose:
    This script creates the tables required for the Silver layer of the 'DataWarehouse' database. 
    Before creating each table, it checks whether the table already exists and drops it if necessary. 
    This ensures that the Silver schema is recreated with a clean structure, ready to store cleansed,
    standardized, and transformed data from the Bronze layer.
    The tables created in this script contain validated and enriched data that has been cleaned, 
    standardized, and prepared for downstream business reporting and analytics. 
    Each table also includes a 'dwh_create_date' column to record when the record was loaded into the
    data warehouse.

Warning:
    Running this script will permanently delete and recreate all existing tables in the Silver schema.
    Any data currently stored in these tables will be lost. 
    Ensure that you have appropriate backups or that the data can be regenerated by reloading and 
    transforming data from the Bronze layer before executing this script.
*/

-- Create 'crm_cust_info' table
IF OBJECT_ID ('silver.crm_cust_info', 'U') IS NOT NULL
	  DROP TABLE silver.crm_cust_info;
CREATE TABLE silver.crm_cust_info(
  	cst_id INT,
  	cst_key	NVARCHAR(50),
  	cst_firstname NVARCHAR(50),
  	cst_lastname NVARCHAR(50),
  	cst_marital_status NVARCHAR(50),
  	cst_gndr NVARCHAR(50),
  	cst_create_date DATE,
    dwh_create_date DATETIME2 DEFAULT GETDATE()
  );

-- Create 'crm_prd_info' table
IF OBJECT_ID ('silver.crm_prd_info', 'U') IS NOT NULL
	  DROP TABLE silver.crm_prd_info;
